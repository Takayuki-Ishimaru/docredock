#!/usr/bin/env python3
"""Generate PDF standard-font widths from pinned PDF.js data, without executing JavaScript.
Use --input-dir for an offline snapshot, or --check to verify the generated source.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
from urllib.request import urlopen

REVISION = "ae842e1c3a75b34344e5c37ca09e497bc49a0d24"
BASE = f"https://raw.githubusercontent.com/mozilla/pdf.js/{REVISION}/src/core/"
HASHES = {
    "metrics.js": "7958e89725c43a152222d5cb6b3b6fcaa6d7995bd9bd6fe18e26d726f56a2a0c",
    "encodings.js": "eee7b0b49fbf0c27fd1765abeea43621c23da3d1a8a592ad0e5ddfe6743658e3",
}
LATIN = ["Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique",
         "Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic"]
TARGET = Path(__file__).resolve().parents[1] / "src/DocRedock.Formats.Pdf/PdfStandardFontMetrics.g.cs"


def read(name, directory):
    if directory:
        data = (directory / name).read_bytes()
    else:
        with urlopen(BASE + name, timeout=30) as response:
            data = response.read()
    if hashlib.sha256(data).hexdigest() != HASHES[name]:
        raise ValueError(f"Unexpected upstream data: {name}")
    return data.decode("utf-8")


def generate(metrics, encodings):
    tables = {}
    for match in re.finditer(r't(?:\.([A-Za-z]+)|\["([A-Za-z-]+)"\]) = getLookupTableFactory\(function \(t\) \{(.*?)\n  \}\);', metrics, re.S):
        name = match[1] or match[2]
        rows = re.findall(r't\.([A-Za-z0-9]+) = (\d+);', match[3])
        tables[name] = {glyph: int(width) for glyph, width in rows}
        if len(rows) != len(tables[name]):
            raise ValueError(f"Duplicate glyph in {name}")
    if set(tables) != set(LATIN + ["Symbol", "ZapfDingbats"]):
        raise ValueError("Unexpected standard-font set")
    if any(len(tables[name]) != 315 for name in LATIN) or len(tables["Symbol"]) != 190 or len(tables["ZapfDingbats"]) != 202:
        raise ValueError("Unexpected glyph counts")
    glyphs = sorted(tables[LATIN[0]])
    if any(set(tables[name]) != set(glyphs) for name in LATIN):
        raise ValueError("Latin glyph sets differ")
    rows = [glyph + " " + " ".join(str(tables[name][glyph]) for name in LATIN) for glyph in glyphs]
    source = f'''// <auto-generated />
// Copyright 2012 Mozilla Foundation. Apache-2.0; see THIRD-PARTY-NOTICES.txt.
// Adapted from PDF.js src/core/metrics.js and encodings.js at {REVISION}.
// Modified: glyph widths grouped by name and converted to C#; no font programs included.
// Regenerate: python3 tools/generate-pdf-standard-metrics.py
using System.Collections.Frozen;
using System.Globalization;

namespace DocRedock.Formats.Pdf;

internal static class PdfStandardFontMetrics
{{
    private static readonly string[] LatinFonts = [{", ".join(json.dumps(name) for name in LATIN)}];
    private static readonly Lazy<FrozenDictionary<string, FrozenDictionary<string, int>>> Metrics = new(Create);

    internal static bool Contains(string name) => name is "Courier" or "Courier-Bold" or "Courier-Oblique" or "Courier-BoldOblique" || Metrics.Value.ContainsKey(name);

    internal static double Width(string font, string glyph) => glyph == ".notdef" ? 0
        : font is "Courier" or "Courier-Bold" or "Courier-Oblique" or "Courier-BoldOblique" ? 600
        : Metrics.Value[font].TryGetValue(glyph, out var width) ? width : double.NaN;

    private static FrozenDictionary<string, FrozenDictionary<string, int>> Create()
    {{
        var fonts = LatinFonts.ToDictionary(name => name, _ => new Dictionary<string, int>(StringComparer.Ordinal), StringComparer.Ordinal);
        foreach (var row in LatinWidths.Split('\\n', StringSplitOptions.RemoveEmptyEntries))
        {{
            var values = row.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            for (var index = 0; index < LatinFonts.Length; index++)
                fonts[LatinFonts[index]].Add(values[0], int.Parse(values[index + 1], CultureInfo.InvariantCulture));
        }}
        foreach (var (name, data) in new[] {{ ("Symbol", SymbolWidths), ("ZapfDingbats", DingbatWidths) }})
        {{
            var widths = new Dictionary<string, int>(StringComparer.Ordinal);
            foreach (var row in data.Split('\\n', StringSplitOptions.RemoveEmptyEntries))
            {{
                var values = row.Split(' ', StringSplitOptions.RemoveEmptyEntries);
                widths.Add(values[0], int.Parse(values[1], CultureInfo.InvariantCulture));
            }}
            fonts.Add(name, widths);
        }}
        return fonts.ToFrozenDictionary(pair => pair.Key, pair => pair.Value.ToFrozenDictionary(StringComparer.Ordinal), StringComparer.Ordinal);
    }}

    private const string LatinWidths = """
'''
    source += "".join("        " + row + "\n" for row in rows) + '        """;\n'
    for font, field in [("Symbol", "SymbolWidths"), ("ZapfDingbats", "DingbatWidths")]:
        source += f'\n    private const string {field} = """\n'
        source += "".join(f"        {glyph} {width}\n" for glyph, width in sorted(tables[font].items()))
        source += '        """;\n'
    for upstream, field in [("SymbolSetEncoding", "SymbolNames"), ("ZapfDingbatsEncoding", "DingbatNames")]:
        match = re.search(r"const " + upstream + r" = (\[.*?\]);", encodings, re.S)
        names = json.loads(match[1])
        if len(names) != 256:
            raise ValueError(f"Unexpected encoding size: {upstream}")
        source += f'\n    internal static readonly string[] {field} =\n    [\n'
        for start in range(0, 256, 8):
            source += "        " + ", ".join(json.dumps(name or ".notdef") for name in names[start:start + 8]) + ",\n"
        source += "    ];\n"
    return source + "}\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate(read("metrics.js", args.input_dir), read("encodings.js", args.input_dir))
    if args.check:
        if TARGET.read_text(encoding="utf-8") != source:
            raise SystemExit(f"Generated table differs: {TARGET}")
    else:
        with TARGET.open("w", encoding="utf-8", newline="\n") as output:
            output.write(source)
    print("Standard 14 font metrics verified." if args.check else "Standard 14 font metrics generated.")


if __name__ == "__main__":
    main()
